"""Render the wiki Evidence page from claims.json.

Standard library only; the output depends on claims.json alone. Run from the
repository root:

    python -I research/evidence/render_evidence.py                 # write Evidence.md
    python -I research/evidence/render_evidence.py --check         # exit 1 if Evidence.md is stale
    python -I research/evidence/render_evidence.py --output PATH   # write the page to PATH instead
"""

from __future__ import annotations

import argparse
import datetime
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CLAIMS = HERE / "claims.json"
PAGE = HERE / "Evidence.md"
WIKI = "https://github.com/Karthik-beta/fiscalclock/wiki/"
VERIFICATION = "https://github.com/Karthik-beta/fiscalclock/blob/main/research/verification/README.md"
MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")
STATUS_ORDER = ("verified", "quote corrected", "fetch failed", "unverified")

HEADER = """\
# Evidence

This page is the claims register: for every factual claim the wiki and the research documents make, it gives the source or reproducible check, the verbatim text or check ID, how it was checked, and the result.

Last reviewed: {reviewed}

**How this page is made.** The page is generated by `research/evidence/render_evidence.py` from the register `research/evidence/claims.json` in the repository, so edit the register, not this page. `research/evidence/check_quotes.py` fetches every source that has a quote and confirms that the quote still appears in it. The Verified column gives the date of the last successful check. The register holds {total} claims: {counts}.

## How to read the register

- **Method.** *Fetched page*: the source page (or API response) was downloaded and the quote compared with its text after removing markup and collapsing whitespace. *Script check*: reproduced by [`research/verification/verify_claims.py`]({verification}), standard-library Python, rerun by CI; the ID is the check name. *Filing*: an SEC filing. *Secondary*: a source that is not the authority for the fact (Wikipedia, a forum post, an archived copy, or a summarised fetch).
- **Status.** *Verified*: the quote or value matches. *Quote corrected*: the source exists but the research documents' wording was not verbatim or overstated it; the corrected wording is given. *Fetch failed*: the script could not fetch the source (it never requests sec.gov); the row says how it was checked instead. *Unverified*: no authoritative source found; treat as an open question.
- The two research documents (the design proposal and the gap analysis) are not published; where a row says "proposal" or "gap analysis", it names the document that made the claim.
"""

FOOTER = """\
## Related pages

- [PDR]({wiki}PDR): requirements and the open questions D1 to D12.
- [Analysis]({wiki}Analysis): the landscape and gap table that use these rows.
- [Testing-Strategy]({wiki}Testing-Strategy): how the conformance vectors relate to `research/verification/`.
"""

COLUMNS = {
    "claims": ("Claim", "Source", "Verbatim quote or check", "Method", "Status", "Verified"),
    "checks": ("ID", "Claim", "Result", "Method", "Status", "Verified"),
    "open": ("Claim", "Where it appears", "What was found", "Status"),
}


def human_date(iso: str) -> str:
    day = datetime.date.fromisoformat(iso)
    return f"{day.day} {MONTHS[day.month - 1]} {day.year}"


def labelled(value: str, note: str | None) -> str:
    text = value[:1].upper() + value[1:]
    return f"{text} ({note})" if note else text


def source(claim: dict) -> str:
    if claim["source_url"]:
        return f"[{claim['source_label']}]({claim['source_url']})"
    return claim["source_label"] or ""


def cells(layout: str, claim: dict) -> tuple[str, ...]:
    method = labelled(claim["method"], claim.get("method_note")) if claim["method"] else ""
    status = labelled(claim["status"], claim.get("status_note"))
    verified = human_date(claim["verified_on"])
    if layout == "claims":
        return (claim["claim"], source(claim), claim["evidence"], method, status, verified)
    if layout == "checks":
        return (claim["check"], claim["claim"], claim["evidence"], method, status, verified)
    return (claim["claim"], claim["appears_in"], claim["evidence"], status)


def table(columns: tuple[str, ...], rows: list[tuple[str, ...]]) -> str:
    def line(values):
        return "| " + " | ".join(v.replace("|", "\\|") for v in values) + " |"
    return "\n".join([line(columns), line(["---"] * len(columns))] + [line(r) for r in rows])


def render(register: dict) -> str:
    claims = register["claims"]
    tally = {status: 0 for status in STATUS_ORDER}
    for claim in claims:
        tally[claim["status"]] += 1
    counts = ", ".join(f"{n} {status}" for status, n in tally.items())
    parts = [HEADER.format(reviewed=human_date(register["last_reviewed"]), total=len(claims),
                           counts=counts, verification=VERIFICATION)]
    for topic in register["topics"]:
        layout = topic["layout"]
        rows = [cells(layout, c) for c in claims if c["topic"] == topic["id"]]
        section = [f"## {topic['heading']}"]
        if topic.get("intro"):
            section.append(topic["intro"])
        section.append(table(COLUMNS[layout], rows))
        if topic.get("outro"):
            section.append(topic["outro"])
        parts.append("\n\n".join(section) + "\n")
    parts.append(FOOTER.format(wiki=WIKI))
    parts.append(f"<!-- cspell:ignore {' '.join(register['cspell_ignore'])} -->\n")
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the committed Evidence.md differs from a fresh render")
    parser.add_argument("--output", type=Path, default=PAGE)
    args = parser.parse_args()

    page = render(json.loads(CLAIMS.read_text(encoding="utf-8")))
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != page:
            print(f"{args.output} is out of date; rerun render_evidence.py", file=sys.stderr)
            return 1
        print(f"{args.output} is up to date")
        return 0
    args.output.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
