// Copies the spec and the changelog from the repository into the docs
// collection as Starlight pages. The repository files stay the source of truth
// and are never modified; the copies are ignored by Git.
//
// Links are rewritten so they work on the site: a link to another imported
// file becomes that page's route, and a link to any other repository path
// becomes its GitHub URL. A relative link to a path that does not exist stops
// the import, so a broken link cannot reach the site.

import { existsSync, mkdirSync, statSync, writeFileSync, readFileSync } from "node:fs";
import { dirname, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const GITHUB = "https://github.com/Karthik-beta/fiscalclock";

/** @typedef {Record<string, { route: string, description: string }>} ImportTable */

// One row per imported file, keyed by its repository path. `route` is the
// page's URL path; the output file is derived from it.
/** @type {ImportTable} */
export const IMPORTS = {
  "spec/definition-v1.md": {
    route: "/reference/spec/definition-v1/",
    description: "The normative calendar definition format, spec version 1: every field, its rules and the error each mistake returns.",
  },
  "spec/api-v1.md": {
    route: "/reference/spec/api-v1/",
    description: "The normative operations, their JSON outputs and the error catalogue, API version 1.",
  },
  "CHANGELOG.md": {
    route: "/project/changelog/",
    description: "Every notable change to fiscalclock, by release.",
  },
};

/** The content-collection file a route is written to, relative to website/. */
export function outputFile(route) {
  return `src/content/docs${route.replace(/\/$/, "")}.md`;
}

const SCHEME = /^[a-z][a-z0-9+.-]*:/i;

/**
 * The site or GitHub URL for one link target in `source`. Returns `null` when
 * the target is a relative path that does not exist in the repository.
 */
export function rewriteLink(target, source, repo, imports = IMPORTS) {
  if (SCHEME.test(target) || target.startsWith("#") || target.startsWith("//")) return target;
  const hashAt = target.indexOf("#");
  const path = hashAt === -1 ? target : target.slice(0, hashAt);
  const hash = hashAt === -1 ? "" : target.slice(hashAt);
  const resolved = path.startsWith("/")
    ? posix.normalize(path.slice(1))
    : posix.normalize(posix.join(posix.dirname(source), path));
  const repoPath = resolved.replace(/\/$/, "");
  if (repoPath === ".." || repoPath.startsWith("../")) return null;
  if (imports[repoPath]) return imports[repoPath].route + hash;
  const onDisk = resolve(repo, repoPath);
  if (!existsSync(onDisk)) return null;
  const kind = statSync(onDisk).isDirectory() ? "tree" : "blob";
  return `${GITHUB}/${kind}/main/${repoPath}${hash}`;
}

// Link targets in Markdown: inline links and images, reference definitions,
// and href/src attributes in raw HTML.
const LINK_PATTERNS = [
  /(\]\()(<[^>]*>|[^)\s]+)/g,
  /^( {0,3}\[[^\]]+\]:\s*)(\S+)/g,
  /((?:href|src)=")([^"]+)/g,
];

/** Rewrites every link in `markdown`, skipping fenced code and code spans. */
export function rewriteLinks(markdown, source, repo, imports = IMPORTS) {
  const broken = [];
  let fence = null;
  const lines = markdown.split("\n").map((line, i) => {
    const marker = line.match(/^ {0,3}(`{3,}|~{3,})/);
    if (marker) {
      if (fence === null) fence = marker[1];
      else if (marker[1].startsWith(fence)) fence = null;
      return line;
    }
    if (fence !== null) return line;
    // Code spans are split out so that link-like text inside them is kept.
    return line
      .split(/(`+[^`]*`+)/)
      .map((part) => {
        if (part.startsWith("`")) return part;
        return LINK_PATTERNS.reduce(
          (text, pattern) =>
            text.replace(pattern, (whole, lead, raw) => {
              const target = raw.replace(/^<|>$/g, "");
              const rewritten = rewriteLink(target, source, repo, imports);
              if (rewritten === null) {
                broken.push(`${source}:${i + 1}: ${target}`);
                return whole;
              }
              return lead + rewritten;
            }),
          part,
        );
      })
      .join("");
  });
  return { markdown: lines.join("\n"), broken };
}

/** The Starlight page for one imported file: frontmatter, a source note, the body without its H1. */
export function toPage(markdown, source, repo, imports = IMPORTS) {
  const { markdown: rewritten, broken } = rewriteLinks(markdown, source, repo, imports);
  const h1 = rewritten.match(/^# (.+)\n+/m);
  if (!h1) return { broken: [`${source}: no level-one heading to use as the title`] };
  const body = rewritten.slice(0, h1.index) + rewritten.slice(h1.index + h1[0].length);
  const page = [
    "---",
    `title: ${JSON.stringify(h1[1].trim())}`,
    `description: ${JSON.stringify(imports[source].description)}`,
    `editUrl: ${GITHUB}/edit/main/${source}`,
    "---",
    "",
    `<!-- Generated by website/scripts/import-docs.mjs from ${source}. Edit that file, not this one. -->`,
    "",
    `This page is a copy of [\`${source}\`](${GITHUB}/blob/main/${source}) in the repository, which is the source of truth.`,
    "",
    body.trimStart(),
  ].join("\n");
  return { page, broken };
}

/**
 * Imports every file in `imports`; writes nothing and throws if any link is broken.
 * @param {string} repo
 * @param {string} website
 * @param {ImportTable} [imports]
 */
export function importDocs(repo, website, imports = IMPORTS) {
  const pages = [];
  const broken = [];
  for (const source of Object.keys(imports)) {
    const result = toPage(readFileSync(resolve(repo, source), "utf8").replace(/\r\n/g, "\n"), source, repo, imports);
    broken.push(...result.broken);
    if (result.page) pages.push({ file: resolve(website, outputFile(imports[source].route)), page: result.page });
  }
  if (broken.length > 0) {
    throw new Error(`import-docs: these links do not resolve to a repository path:\n  ${broken.join("\n  ")}`);
  }
  for (const { file, page } of pages) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, page);
  }
  return pages.map(({ file }) => file);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const website = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  try {
    const written = importDocs(resolve(website, ".."), website);
    console.log(`import-docs: wrote ${written.length} pages`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
